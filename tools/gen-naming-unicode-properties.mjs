// Generate naming-convention's ECMAScript Unicode property ranges.
// Usage: node tools/gen-naming-unicode-properties.mjs /path/to/typescript-eslint
// Input packages are pinned in that checkout's node_modules.
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';

const checkout = process.argv[2];
if (!checkout) throw new Error('Pass the typescript-eslint checkout containing pinned node_modules');
const pnpm = path.join(checkout, 'node_modules', '.pnpm');
const packageRoot = (name, version) => path.join(pnpm, `${name}@${version}`, 'node_modules', name);
const rangesRoot = packageRoot('regenerate-unicode-properties', '10.2.2');
const valueAliasRoot = packageRoot('unicode-match-property-value-ecmascript', '2.2.1');
const propertyAliasRoot = packageRoot('unicode-property-aliases-ecmascript', '2.2.0');
for (const [root, version] of [[rangesRoot, '10.2.2'], [valueAliasRoot, '2.2.1'], [propertyAliasRoot, '2.2.0']]) {
  const actual = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8')).version;
  if (actual !== version) throw new Error(`Expected ${version}, found ${actual} at ${root}`);
}
const require = createRequire(import.meta.url);
const valueAliases = require(path.join(valueAliasRoot, 'data', 'mappings.js'));
const propertyAliases = require(propertyAliasRoot);
const groups = ['Binary_Property', 'General_Category', 'Script', 'Script_Extensions'];
let go = `// Code generated by tools/gen-naming-unicode-properties.mjs; DO NOT EDIT.\n`;
go += `// Source: regenerate-unicode-properties@10.2.2,\n`;
go += `// unicode-match-property-value-ecmascript@2.2.1, and\n`;
go += `// unicode-property-aliases-ecmascript@2.2.0.\n`;
const rangeLicense = fs.readFileSync(path.join(rangesRoot, 'LICENSE-MIT.txt'), 'utf8');
for (const root of [valueAliasRoot, propertyAliasRoot]) {
  if (fs.readFileSync(path.join(root, 'LICENSE-MIT.txt'), 'utf8') !== rangeLicense) {
    throw new Error('Source license texts differ');
  }
}
for (const line of rangeLicense.trimEnd().split('\n')) go += `// ${line}\n`;
go += `\npackage naming_convention\n\n`;
go += `// Each pair is a half-open code-point range.\n`;
go += `var namingPropertyRangesByName = map[string][]uint32{\n`;
const namesByGroup = new Map();
for (const group of groups) {
  const directory = path.join(rangesRoot, group);
  const names = fs.readdirSync(directory).filter(name => name.endsWith('.js')).map(name => name.slice(0, -3)).sort();
  namesByGroup.set(group, new Set(names));
  for (const name of names) {
    const pairs = require(path.join(directory, `${name}.js`)).characters.data;
    go += `\t${JSON.stringify(`${group}=${name}`)}: {${pairs.map(cp => `0x${cp.toString(16)}`).join(', ')}},\n`;
  }
}
go += `}\n\n`;
go += `var namingPropertyNameAliases = map[string]string{\n`;
for (const [alias, canonical] of [...propertyAliases].sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0)) {
  go += `\t${JSON.stringify(alias)}: ${JSON.stringify(canonical)},\n`;
}
go += `}\n\n`;
go += `var namingPropertyValueAliases = map[string]map[string]string{\n`;
for (const group of groups.slice(1)) {
  go += `\t${JSON.stringify(group)}: {\n`;
  for (const [alias, canonical] of valueAliases.get(group)) {
    if (namesByGroup.get(group).has(canonical)) go += `\t\t${JSON.stringify(alias)}: ${JSON.stringify(canonical)},\n`;
  }
  go += `\t},\n`;
}
go += `}\n`;
const output = path.join(process.cwd(), 'internal', 'rules', 'naming_convention', 'unicode_properties_generated.go');
fs.writeFileSync(output, go);
execFileSync('gofmt', ['-w', output]);
console.log(`Generated ${output}: ${[...namesByGroup].map(([group, names]) => `${group}=${names.size}`).join(', ')}`);
